#!/usr/bin/env bash
# 架构约束门禁 —— 钉住「重构之后不许再长回去」的那几条性质。
#
# 这些约束**没有任何编译器/linter 会管**:违反它的代码编译通过、测试全绿,
# 只是把一个已经收敛的路径重新叉开,然后两条叉路开始各自漂。
#
# 每条门禁一个文件,在 scripts/arch/ 下,可以单独跑(重构中修某一条时很有用):
#
#     ./scripts/arch/50-dependency-direction.sh
#
# ---------- 两种形态,别混 ----------
#
# ①②③ 是**硬约束**:今天就是 0 违规,新增一条即红。
# ④⑤⑥⑦⑧ 是**棘轮**:本仓库的架构债是三年长出来的,一条「必须为 0」的门禁在
# 今天就是红的,而**红着的门禁等于没有门禁** —— 人会 `|| true` 掉它。
# 所以它们把今天的违规逐条登记进 scripts/lib/arch-baseline/,然后:
#   · 出现基线外的新违规 → 红(「避免后续再犯」)
#   · 基线里的条目被修好了却没删 → **也红**(保证基线真的在缩)
#
# 那批基线文件同时就是**重构的 TODO 清单** —— 每行带一句「为什么它还在」。
set -uo pipefail
cd "$(dirname "$0")/.."

fail=0
for gate in scripts/arch/[0-9]*.sh; do
    "$gate" || fail=1
done

if [ "$fail" -ne 0 ]; then
    echo >&2
    echo "FAIL: 架构约束违规(见上)。" >&2
    echo "⛔ 想「先合进去回头再修」之前:上面每条都写了改法,大多是一处调用点的事。" >&2
    exit 1
fi
echo "ok: 架构约束"
